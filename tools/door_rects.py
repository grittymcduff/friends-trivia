#!/usr/bin/env python3
"""Where the door is painted on every street front, so the game can outline it (v2.0.6).

Door rectangles on the eleven Village facades were measured from the art, in tiles:
(left, right) from the facade's left edge, (top, bottom) as heights above the facade's bottom.
The composite fronts made by prep_streets.py are side-by-side stretched copies of those, so their
doors follow from the same layout. Writes src/doorart.js (DOOR_ART: facade id -> [[x0,x1,top,bottom], ...]).

Usage: python3 -I tools/door_rects.py
"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import prep_streets as ps  # noqa: E402

BASE = {
    "n1_brownstone":      [(0.66, 1.75, 2.75, 1.0)],
    "n2_brick":           [(0.47, 1.44, 2.19, 0.45)],
    "n3_central_perk":    [(0.47, 1.56, 1.81, 0.25), (6.17, 7.42, 2.72, 0.72)],
    "n4_brick_ross":      [(1.22, 2.5, 2.69, 1.0)],
    "n5_brownstone":      [(0.5, 1.64, 2.9, 1.0)],
    "n6_rays_pizza":      [(0.81, 1.75, 1.75, 0.14)],
    "s1_lucille_lortel":  [(2.66, 5.39, 2.44, 0.03)],
    "s2_brownstone":      [(0.66, 1.88, 3.3, 1.5)],
    "s3_village_cigars":  [(1.06, 1.97, 1.9, 0.25)],
    "s4_brick_phoebe":    [(0.81, 1.88, 2.56, 0.9)],
    "s5_brownstone_wide": [(0.97, 2.03, 2.88, 0.88)],
}


def main():
    out = {k: [list(r) for r in v] for k, v in BASE.items()}
    for name, (w, parts, _col, _main) in ps.BUILDINGS.items():
        sx = w / sum(ps.LIB[p][0] for p in parts)
        x, rects = 0.0, []
        for p in parts:
            for (a, b, t, bt) in BASE[p]:
                rects.append([round(x + a * sx, 3), round(x + b * sx, 3), t, bt])
            x += ps.LIB[p][0] * sx
        out["x_" + name] = rects
    js = ("// generated by tools/door_rects.py: painted door rectangles per street front, in tiles\n"
          "const DOOR_ART=" + json.dumps(out, separators=(",", ":")) + ";\n")
    (Path(__file__).resolve().parent.parent / "src" / "doorart.js").write_text(js)
    print(len(out), "fronts")


if __name__ == "__main__":
    main()
